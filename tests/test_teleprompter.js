'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const presenter=require('../static/teleprompter.js');
const input=JSON.parse(fs.readFileSync(0,'utf8'));
const calls=[];
const ctx={font:'',fillStyle:'',fillRect(){},measureText(text){return {width:text.length*parseFloat(this.font.split(' ')[1])*.5};},fillText(text,x,y){calls.push({text,x,y});}};
const canvas={width:0,height:0,getContext(){return ctx;}};
const state=presenter.snapshot(input.project,3400,input.duration);
presenter.draw(canvas,input.project,state);
for(const value of ['UPLYNULO','DO KONCA','TERAZ','PREDCHÁDZAJÚCI TEXT','NASLEDUJÚCI TEXT',state.elapsed,state.remaining,state.countdownLabel,String(state.countdown)])assert.ok(calls.some(call=>call.text===value),value);
const previous=calls.find(call=>call.text===input.project.segments[0].text);
const current=calls.find(call=>call.text===input.project.segments[1].text);
const next=calls.find(call=>call.text===input.project.segments[2].text);
assert.ok(previous&&current&&next,'all three prompt texts must be visible');
assert.ok(previous.y<current.y&&current.y<next.y,'prompt areas stay in their fixed order');
assert.equal(canvas.width,input.project.style.width);
assert.equal(canvas.height,input.project.style.height);
process.stdout.write(JSON.stringify(input.times.map(time=>presenter.snapshot(input.project,time,input.duration))));
